CREATE DATABASE IF NOT EXISTS inkspell_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE inkspell_db;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, full_name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role ENUM('USER','ADMIN') NOT NULL DEFAULT 'USER', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS genres (id INT PRIMARY KEY AUTO_INCREMENT,name VARCHAR(60) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS books (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,title VARCHAR(200) NOT NULL,author VARCHAR(150) NOT NULL,genre_id INT NOT NULL,
 description TEXT NOT NULL,cover_image_url VARCHAR(1000),isbn VARCHAR(13),publication_year INT,total_pages INT,
 is_featured BOOLEAN NOT NULL DEFAULT 0,is_demo BOOLEAN NOT NULL DEFAULT 0,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(genre_id) REFERENCES genres(id),INDEX(title),INDEX(author),INDEX(genre_id),CHECK(total_pages IS NULL OR total_pages>0)
);
CREATE TABLE IF NOT EXISTS user_library (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,book_id BIGINT NOT NULL,
 reading_status ENUM('WANT_TO_READ','CURRENTLY_READING','COMPLETED') NOT NULL DEFAULT 'WANT_TO_READ',current_page INT NOT NULL DEFAULT 0,total_pages_override INT,
 date_added TIMESTAMP DEFAULT CURRENT_TIMESTAMP,date_started DATE,date_completed DATE,personal_notes TEXT,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE(user_id,book_id),FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,FOREIGN KEY(book_id) REFERENCES books(id),CHECK(current_page>=0),CHECK(total_pages_override IS NULL OR total_pages_override>0)
);
CREATE TABLE IF NOT EXISTS ratings (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,book_id BIGINT NOT NULL,rating TINYINT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE(user_id,book_id),CHECK(rating BETWEEN 1 AND 5),FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,FOREIGN KEY(book_id) REFERENCES books(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS bookmarks (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,book_id BIGINT NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,book_id),FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,FOREIGN KEY(book_id) REFERENCES books(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS user_preferred_genres (
 user_id BIGINT NOT NULL,genre_id INT NOT NULL,PRIMARY KEY(user_id,genre_id),FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,FOREIGN KEY(genre_id) REFERENCES genres(id)
);
CREATE TABLE IF NOT EXISTS site_testimonials (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,quote VARCHAR(1000) NOT NULL,name VARCHAR(100) NOT NULL,label VARCHAR(100) NOT NULL,
 is_placeholder BOOLEAN NOT NULL DEFAULT 0,sort_order INT NOT NULL DEFAULT 0,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS site_content (`key` VARCHAR(100) PRIMARY KEY,`value` TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS user_reading_goals (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,year INT NOT NULL,target_books INT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE(user_id,year),FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,CHECK(target_books>0)
);
CREATE TABLE IF NOT EXISTS reading_activity (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,book_id BIGINT,
 activity_type VARCHAR(40) NOT NULL,description VARCHAR(255) NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,FOREIGN KEY(book_id) REFERENCES books(id) ON DELETE SET NULL,INDEX(user_id,created_at)
);

